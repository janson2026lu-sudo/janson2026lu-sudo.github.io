window.getCaseGuide=function(c){
  const t=(c.title||"")+" "+(c.scenario||"");
  let category="需求与范围";
  if(/挣值|CPI|SPI|关键路径|赶工|工期/.test(t)) category="挣值与进度";
  else if(/变更|范围蔓延|口头提出/.test(t)) category="变更管理";
  else if(/质量|缺陷/.test(t)) category="质量管理";
  else if(/采购|供应商|外包|合同|验收争议/.test(t)) category="采购管理";
  else if(/干系人|沟通/.test(t)) category="沟通与干系人";
  else if(/配置|版本|发布|受控需求/.test(t)) category="配置管理";
  else if(/风险|离职/.test(t)) category="风险管理";
  else if(/收尾|移交|尾款/.test(t)) category="收尾与移交";
  else if(/需求|范围基线/.test(t)) category="需求与范围";
  else if(/数据|迁移|权限|备份|安全/.test(t)) category="数据与安全";
  else if(/运维|故障|事件|问题管理|服务/.test(t)) category="服务与运维";
  const guide={category,template:window.CASE_TEMPLATES[category]||[]};
  if(/案例2：挣值分析/.test(c.title||"")){
    guide.reference=[
      "PV=100×60%=60万元；EV=100×50%=50万元；AC=65万元。",
      "CV=EV-AC=50-65=-15万元，小于0，说明成本超支。",
      "SV=EV-PV=50-60=-10万元，小于0，说明进度落后。",
      "CPI=EV/AC=50/65≈0.77，小于1；SPI=EV/PV=50/60≈0.83，小于1。",
      "改进时应优先分析关键路径、资源瓶颈、返工、采购与质量问题，形成纠偏措施；如涉及基准调整，应按变更控制流程处理。"
    ];
  } else if(/近期案例考点重构1/.test(c.title||"")){
    guide.reference=[
      "先根据活动逻辑关系和持续时间计算各条路径总工期，持续时间最长的路径为关键路径。",
      "PV为计划价值，EV为已完成工作的预算价值，AC为实际成本。",
      "SPI=EV/PV：小于1表示进度落后；CPI=EV/AC：小于1表示成本效率不佳。",
      "若题设说明当前成本效率会持续，可采用EAC=BAC/CPI，ETC=EAC-AC或(BAC-EV)/CPI。",
      "最后结合关键路径、资源配置、返工、采购和质量原因提出纠偏措施，并持续监控效果。"
    ];
  }
  return guide;
};